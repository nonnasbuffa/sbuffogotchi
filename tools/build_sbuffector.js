// Builds Sbuffector's game knowledge from the game itself, so she always knows everything players can see.
// Run before deploying the chat server:  node tools/build_sbuffector.js && (cd server/chat-worker && npx wrangler deploy)
// It reads every English text in www/i18n.js (minus the admin terminal's) and writes server/chat-worker/knowledge.js.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'www/i18n.js'), 'utf8');
const a = src.indexOf('\n    en: {'), b = src.indexOf('\n    es: {');
if (a < 0 || b < 0) throw new Error('could not find the English texts in i18n.js');
const en = vm.runInNewContext(`({${src.slice(a, b).trim().replace(/,\s*$/, '')}})`).en;

// The admin terminal is secret: its help and messages (tm_*, h_*) stay out.
const hidden = (k, v) => /^(tm_|h_|admin|cheat|beta)/i.test(k) || /^term/i.test(k) || /admin|cheat|terminal/i.test(v);
const lines = Object.entries(en)
  .filter(([k, v]) => typeof v === 'string' && !hidden(k, v))
  .map(([k, v]) => `${k}: ${v.replace(/\s+/g, ' ')}`);

const out = `// Generated by tools/build_sbuffector.js from www/i18n.js. Don't edit by hand: run the tool again.
export const GAME_TEXT = ${JSON.stringify(lines.join('\n'))};
`;
fs.writeFileSync(path.join(root, 'server/chat-worker/knowledge.js'), out);
console.log(`knowledge.js: ${lines.length} texts, ${Math.round(out.length / 1024)} KB`);
